# shellcheck shell=bash disable=SC2154 # line_dir, line_pkgrel and repl are the caller's
# The shared part of scripts/gen-cuda12.sh and scripts/gen-migraphx.sh, the
# generators of the recipes of the other lines of onnxruntime-split
# (onnxruntime-split-cuda12, onnxruntime-split-migraphx): sourced by them,
# not run. The caller sets
#   line_dir    the generated recipe's directory name (and pkgbase), e.g.
#               onnxruntime-split-cuda12
#   line_pkgrel that line's own pkgrel
#   repl        an associative array, name -> the line(s) that replace the
#               source's top-level name=... line (pkgrel is added here:
#               pkgrel=$line_pkgrel, with a comment that it is the line's
#               own)
# and calls gen_line_main "$@".
#
# The generated file is onnxruntime-split/PKGBUILD with those lines
# replaced, and a comment after the Maintainer line saying it is
# generated, and nothing else changed (the same pkgver, sources, checksums
# and build). Each of those source lines (a whole line beginning with the
# name and =) must occur exactly once, or nothing is written: a source that
# no longer has one breaks the generator loudly instead of yielding a
# recipe that builds the main line. The source's _ortf_core_abi_pkgrel (the
# core pkgrel the generated lines pin from) must occur once and be no
# higher than its pkgrel, or nothing is written: after a pkgver bump
# (pkgrel back to 1) it must be reset too. Writing a file already up to
# date leaves it untouched.
#
#   <generator>            # writes <line_dir>/PKGBUILD
#   <generator> --check    # fails, with a diff, when the committed one is
#                          # stale
#
# After a change, scripts/srcinfo.sh --recipe <line_dir> --write
# regenerates its .SRCINFO.
# Exit status: 0 done (or up to date), 1 stale, 2 usage error, a source
# line missing or repeated, or an ABI pkgrel above the pkgrel.

# gen_line_main <arguments...>: the generator's whole run.
gen_line_main() {
    local prog=${0##*/} top src dest_dir dest mode=write tmp banner
    top=$(cd "$(dirname "$0")/.." && pwd)
    src=$top/onnxruntime-split/PKGBUILD
    dest_dir=$top/$line_dir
    dest=$dest_dir/PKGBUILD
    case ${1:-} in
        '') (($# == 0)) || gen_line_usage ;;
        --check) (($# == 1)) || gen_line_usage; mode=check ;;
        *) gen_line_usage ;;
    esac
    if [[ ! -f $src ]]; then
        echo "$prog: $src not found" >&2
        exit 2
    fi
    repl['pkgrel']="# $line_dir's own pkgrel (scripts/$prog); the
# notes above are those of onnxruntime-split's.
pkgrel=$line_pkgrel"
    banner="# Generated by scripts/$prog from onnxruntime-split/PKGBUILD
# (https://github.com/rsd/omarchy-onnxruntime): do not edit; change the
# source and regenerate."

    tmp=$(mktemp -d)
    # shellcheck disable=SC2064 # expanded now: tmp is local
    trap "rm -rf '$tmp'" EXIT
    gen_line_generate "$src" "$tmp/PKGBUILD" || exit

    case $mode in
        write)
            if [[ -f $dest ]] && cmp -s -- "$tmp/PKGBUILD" "$dest"; then
                echo "$line_dir/PKGBUILD is up to date"
            else
                mkdir -p -- "$dest_dir"
                cp -- "$tmp/PKGBUILD" "$dest.tmp"
                mv -f -- "$dest.tmp" "$dest"
                echo "wrote $dest; then run scripts/srcinfo.sh --recipe $line_dir --write"
            fi
            ;;
        check)
            if [[ ! -f $dest ]]; then
                echo "$prog: $dest does not exist: run $prog" >&2
                exit 1
            fi
            if ! diff -u --label "committed $line_dir/PKGBUILD" --label "generated" \
                "$dest" "$tmp/PKGBUILD"; then
                echo "$prog: $line_dir/PKGBUILD is stale: run $prog" >&2
                exit 1
            fi
            echo "$line_dir/PKGBUILD is up to date"
            ;;
    esac
}

gen_line_usage() {
    echo "usage: ${0##*/} [--check]" >&2
    exit 2
}

# gen_line_generate <source> <file>: writes the generated PKGBUILD to
# <file> (uses repl and banner).
gen_line_generate() {
    local line name bad=0 maint=0 prog=${0##*/} src_rel='' abi_rel='' abi_n=0
    local -A seen=()
    local -a out=()
    while IFS= read -r line || [[ -n $line ]]; do
        name=''
        [[ ! $line =~ ^([A-Za-z_][A-Za-z0-9_]*)= ]] || name=${BASH_REMATCH[1]}
        [[ $name != pkgrel ]] || src_rel=${line#pkgrel=}
        if [[ $name == _ortf_core_abi_pkgrel ]]; then
            abi_rel=${line#*=}
            abi_n=$((abi_n + 1))
        fi
        if [[ -n $name && -n ${repl[$name]+x} ]]; then
            seen[$name]=$((${seen[$name]:-0} + 1))
            out+=("${repl[$name]}")
        else
            out+=("$line")
        fi
        if [[ $line == '# Maintainer: '* ]]; then
            maint=$((maint + 1))
            out+=('#' "$banner")
        fi
    done <"$1"
    for name in "${!repl[@]}"; do
        if [[ ${seen[$name]:-0} != 1 ]]; then
            echo "$prog: $1 has ${seen[$name]:-0} lines $name=..., not exactly one" >&2
            bad=1
        fi
    done
    if ((maint != 1)); then
        echo "$prog: $1 has $maint '# Maintainer: ' lines, not exactly one" >&2
        bad=1
    fi
    # The other lines pin onnxruntime-core>=<pkgver>-<_ortf_core_abi_pkgrel>:
    # above the source's own pkgrel, no core of this pkgver would meet it.
    if ((abi_n != 1)); then
        echo "$prog: $1 has $abi_n lines _ortf_core_abi_pkgrel=..., not exactly one" >&2
        bad=1
    elif [[ ! $abi_rel =~ ^[1-9][0-9]*$ || ! $src_rel =~ ^[1-9][0-9]*$ ]]; then
        echo "$prog: $1: _ortf_core_abi_pkgrel=$abi_rel and pkgrel=$src_rel must be positive integers" >&2
        bad=1
    elif ((abi_rel > src_rel)); then
        echo "$prog: $1: _ortf_core_abi_pkgrel=$abi_rel is above pkgrel=$src_rel: the other lines would pin an onnxruntime-core that does not exist; after a pkgver bump, reset _ortf_core_abi_pkgrel to the new pkgrel (1)" >&2
        bad=1
    fi
    ((bad == 0)) || return 2
    printf '%s\n' "${out[@]}" >"$2"
}
