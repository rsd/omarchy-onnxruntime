#!/usr/bin/env bash
# Tests for scripts/gen-migraphx.sh and the committed
# onnxruntime-split-migraphx/PKGBUILD and .SRCINFO: --check passes on the
# tree; the committed file differs from onnxruntime-split/PKGBUILD in the
# stamped lines only (pkgbase, the default inputs migraphx and no Python,
# _ortf_line=migraphx, its own pkgrel 1); its onnxruntime-core pin is the
# source's pair; the committed .SRCINFO has the one MIGraphX package, the
# pin pair, Arch's migraphx and hip-runtime-amd, and no CUDA, OpenVINO,
# Python module or -bin; on a copy of the scripts and the recipes (under
# mktemp) a run on an up-to-date file is a no-op, an altered or missing
# generated file fails --check (exit 1, with a diff) and a run mends it, and
# a source that lacks a stamped line, or has one twice, fails (exit 2) and
# writes nothing; usage errors exit 2; git ignores makepkg's work files
# there, not the recipe, and the licence guard would not refuse it.
# Usage: scripts/tests/gen-migraphx-test.sh. Exits non-zero on any failure.
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
top=$(cd "$here/../.." && pwd)
src=$top/onnxruntime-split/PKGBUILD
gen=$top/onnxruntime-split-migraphx/PKGBUILD
si=$top/onnxruntime-split-migraphx/.SRCINFO

fails=0 count=0
ok() { count=$((count + 1)); echo "ok   $1"; }
fail() { count=$((count + 1)); echo "FAIL $1"; fails=$((fails + 1)); }

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

echo "== the tree"
if out=$("$top/scripts/gen-migraphx.sh" --check 2>&1); then ok "--check passes on the tree"; else
    fail "--check on the tree: $out"; fi
# The stamped lines, and nothing else (diff's own lines, <source >generated).
want=$(
    cat <<'EOF'
> # Generated by scripts/gen-migraphx.sh from onnxruntime-split/PKGBUILD
> # (https://github.com/rsd/omarchy-onnxruntime): do not edit; change the
> # source and regenerate.
> #
< pkgbase=onnxruntime-split
> pkgbase=onnxruntime-split-migraphx
< _ortf_default_eps='cuda tensorrt openvino dnnl webgpu'
> _ortf_default_eps='migraphx'
< _ortf_default_python=1
> _ortf_default_python=0
< _ortf_line=main
> _ortf_line=migraphx
EOF
)
got=$(diff "$src" "$gen" | grep '^[<>]' | grep -v -e '^< pkgrel=' -e '^> pkgrel=' \
    -e "^> # onnxruntime-split-migraphx's own pkgrel" -e "^> # notes above are those of onnxruntime-split's." || true)
if [[ $got == "$want" ]]; then ok "the generated file differs from the source in the stamped lines only"; else
    fail "the differences: $(diff <(echo "$want") <(echo "$got"))"; fi
if grep -qxF 'pkgrel=1' "$gen" && (($(grep -c '^pkgrel=' "$gen") == 1)) &&
    grep -qxF "# onnxruntime-split-migraphx's own pkgrel (scripts/gen-migraphx.sh); the" "$gen"; then
    ok "its own pkgrel, 1, with a comment saying so"
else
    fail "the pkgrel lines: $(grep -n 'pkgrel=' "$gen")"
fi
if [[ $(sed -n 1p "$gen") == "$(sed -n 1p "$src")" && $(sed -n 3p "$gen") == '# Generated by scripts/gen-migraphx.sh from onnxruntime-split/PKGBUILD' ]]; then
    ok "the Maintainer line first, then the generated-file notice"
else
    fail "the top of the generated file: $(head -n 4 "$gen")"
fi

echo "== its committed .SRCINFO"
T=$'\t'
if [[ -r $si ]]; then
    names=$(sed -n 's/^pkgname = //p' "$si" | tr '\n' ' ')
    if [[ $names == 'onnxruntime-provider-migraphx python-onnxruntime-provider-migraphx ' ]] &&
        grep -qxF 'pkgbase = onnxruntime-split-migraphx' "$si"; then
        ok "two packages, onnxruntime-provider-migraphx and its Python add-on python-onnxruntime-provider-migraphx, of pkgbase onnxruntime-split-migraphx"
    else
        fail "pkgbase and names: $names"
    fi
    missing=''
    for line in "${T}pkgrel = 1" "${T}depends = onnxruntime-core>=1.29.0-7" "${T}depends = onnxruntime-core<1.29.1" \
        "${T}depends = migraphx" "${T}depends = hip-runtime-amd" "${T}makedepends = migraphx" \
        "${T}makedepends = hip-runtime-amd" \
        "${T}pkgdesc = The MIGraphX execution provider of ONNX Runtime, for onnxruntime-core (AMD GPUs; untested on AMD hardware)"; do
        grep -qxF -- "$line" "$si" || missing+=" [$line]"
    done
    if [[ -z $missing ]]; then ok "the pin pair on the main line's core, ROCm depends and makedepends, untested pkgdesc"; else
        fail ".SRCINFO lacks$missing"; fi
    # Not a single CUDA, OpenVINO, TensorRT or Python-module name and no
    # -bin anywhere, but the provider's optdepend on its Python add-on and
    # the add-on's own block (it links the provider's library into the main
    # line's Python module, and so depends on python); no oneDNN but in the
    # sources every line shares (the same source= as the main line's); no
    # bare or pkgver-only core pin (a training-off core meets either).
    mgx_opt="${T}optdepends = python-onnxruntime-provider-migraphx: MIGraphX from Python (MIGraphXExecutionProvider in python-onnxruntime-core)"
    mgx_py=$(sed -n '/^pkgname = python-onnxruntime-provider-migraphx$/,/^$/p' "$si")
    mgx_prov=$(sed -n '/^pkgname = onnxruntime-provider-migraphx$/,/^$/p' "$si")
    if bad=$(grep -vxF -- "$mgx_opt" "$si" | sed '/^pkgname = python-onnxruntime-provider-migraphx$/,/^$/d' |
        grep -nEi -- 'cuda|openvino|tensorrt|python-|-bin\b'); then
        fail "the .SRCINFO names: $bad"
    elif ! grep -qxF -- "$mgx_opt" <<<"$mgx_prov" || grep -qE "^${T}depends = python" <<<"$mgx_prov"; then
        fail "the provider block lacks the add-on optdepend, or depends on python: $mgx_prov"
    elif [[ $(sed -n "s/^${T}depends = //p" <<<"$mgx_py" | tr '\n' ' ') != \
        'onnxruntime-provider-migraphx=1.29.0-1 python-onnxruntime-core>=1.29.0-7 python-onnxruntime-core<1.29.1 python ' ]] ||
        ! grep -qxF "${T}conflicts = onnxruntime-core-nccloff" <<<"$mgx_py" || grep -qE "^${T}(provides|optdepends) = " <<<"$mgx_py"; then
        fail "the add-on block: $mgx_py"
    else
        ok "no CUDA, OpenVINO, TensorRT, Python module or -bin in it; the provider without python, its add-on optdepend; the add-on on the provider (exact), the Python module (pin pair) and python"
    fi
    if bad=$(grep -vE -- "^${T}(source|noextract) = " "$si" | grep -nEi -- 'dnnl|onednn'); then
        fail "oneDNN outside the sources: $bad"
    else
        ok "no oneDNN package, depend or build input"
    fi
    if bad=$(grep -nE -- "^${T}depends = onnxruntime-core(=.*)?\$" "$si"); then fail "a core pin outside the pair: $bad"; else
        ok "no pin a core built without the training ops meets"; fi
else
    fail "$si not found"
fi
if git -C "$top" check-ignore -q onnxruntime-split-migraphx/PKGBUILD || git -C "$top" check-ignore -q onnxruntime-split-migraphx/.SRCINFO; then
    fail "git ignores the recipe or its .SRCINFO"
else
    ok "git does not ignore onnxruntime-split-migraphx/PKGBUILD and .SRCINFO"
fi
for f in src/x pkg/x onnxruntime/x ortf-dep-onnx.zip ortf-dep-onednn.zip; do
    if git -C "$top" check-ignore -q "onnxruntime-split-migraphx/$f"; then ok "git ignores onnxruntime-split-migraphx/$f"; else
        fail "git does not ignore onnxruntime-split-migraphx/$f (makepkg's work files)"; fi
done
if ! grep -qiE "$(sed -n "s/^    -e '\(copyright[^']*\)'.*/\1/p" "$top/scripts/check-no-vendor.sh" | paste -sd '|')" "$gen" &&
    ! LC_ALL=C grep -q '[^[:print:][:space:]]' "$gen" && (($(wc -c <"$gen") < 1048576)); then
    ok "the generated PKGBUILD is small plain text without a vendor copyright line"
else
    fail "the generated PKGBUILD would trip the licence guard"
fi

echo "== a copy of the scripts and the recipes"
copy=$tmp/repo
mkdir -p "$copy/scripts" "$copy/onnxruntime-split" "$copy/onnxruntime-split-migraphx"
cp "$top/scripts/gen-migraphx.sh" "$top/scripts/gen-line-lib.sh" "$copy/scripts/"
cp "$src" "$copy/onnxruntime-split/"
cp "$gen" "$copy/onnxruntime-split-migraphx/"
cgen=$copy/onnxruntime-split-migraphx/PKGBUILD
if "$copy/scripts/gen-migraphx.sh" --check >/dev/null 2>&1; then ok "the copy checks out"; else
    fail "the unaltered copy fails --check"; fi
touch -d '2000-01-01 00:00' "$cgen"
before=$(stat -c %Y "$cgen")
if out=$("$copy/scripts/gen-migraphx.sh" 2>&1) && grep -qF 'is up to date' <<<"$out" &&
    [[ $(stat -c %Y "$cgen") == "$before" ]] && cmp -s "$cgen" "$gen"; then
    ok "a run on an up-to-date file leaves it untouched"
else
    fail "a second run: $out"
fi
sed -i 's/^pkgrel=1$/pkgrel=2/' "$cgen"
status=0
out=$("$copy/scripts/gen-migraphx.sh" --check 2>&1) || status=$?
if ((status == 1)) && grep -qxF -- '-pkgrel=2' <<<"$out" && grep -qxF -- '+pkgrel=1' <<<"$out" &&
    grep -qF 'onnxruntime-split-migraphx/PKGBUILD is stale: run gen-migraphx.sh' <<<"$out"; then
    ok "an altered generated file fails --check (exit 1) with a diff"
else
    fail "an altered generated file (exit $status): $out"
fi
if "$copy/scripts/gen-migraphx.sh" >/dev/null && "$copy/scripts/gen-migraphx.sh" --check >/dev/null && cmp -s "$cgen" "$gen"; then
    ok "a run mends it, to the committed one"
else
    fail "a run did not restore the generated file"
fi
sed -i 's/^pkgver=1.29.0$/pkgver=1.29.1/' "$copy/onnxruntime-split/PKGBUILD"
status=0
out=$("$copy/scripts/gen-migraphx.sh" --check 2>&1) || status=$?
if ((status == 1)) && grep -qxF -- '+pkgver=1.29.1' <<<"$out"; then ok "a changed source makes the generated file stale"; else
    fail "a changed source (exit $status): $out"; fi
rm "$cgen"
status=0
out=$("$copy/scripts/gen-migraphx.sh" --check 2>&1) || status=$?
if ((status == 1)) && grep -qF 'does not exist' <<<"$out"; then ok "a missing generated file fails --check"; else
    fail "a missing generated file (exit $status): $out"; fi
rm -r "$copy/onnxruntime-split-migraphx"
if "$copy/scripts/gen-migraphx.sh" >/dev/null && [[ -f $cgen ]] && grep -qxF 'pkgbase=onnxruntime-split-migraphx' "$cgen"; then
    ok "a run creates the directory and the file, stamped"
else
    fail "a run without onnxruntime-split-migraphx/"
fi

# NCCL is stamped on (the plug rule: every line built alike), whatever
# the source's default.
sed 's/^_ortf_default_nccl=.*/_ortf_default_nccl=0/' "$src" >"$copy/onnxruntime-split/PKGBUILD"
if "$copy/scripts/gen-migraphx.sh" >/dev/null && grep -qxF '_ortf_default_nccl=1' "$cgen" &&
    ! grep -q '^_ortf_default_nccl=0' "$cgen"; then
    ok "_ortf_default_nccl=1 is stamped, whatever the source's default"
else
    fail "the NCCL stamp: $(grep -n '^_ortf_default_nccl=' "$cgen")"
fi
cp "$src" "$copy/onnxruntime-split/PKGBUILD"
"$copy/scripts/gen-migraphx.sh" >/dev/null

echo "== a source that drifted"
cp "$src" "$copy/onnxruntime-split/PKGBUILD"
"$copy/scripts/gen-migraphx.sh" >/dev/null
for name in pkgbase _ortf_default_eps _ortf_default_python _ortf_default_nccl _ortf_line pkgrel; do
    line=$(grep -m1 "^$name=" "$src")
    for how in removed doubled; do
        if [[ $how == removed ]]; then
            grep -v "^$name=" "$src" >"$copy/onnxruntime-split/PKGBUILD"
            n=0
        else
            sed "/^$name=/p" "$src" >"$copy/onnxruntime-split/PKGBUILD"
            n=2
        fi
        status=0
        out=$("$copy/scripts/gen-migraphx.sh" 2>&1) || status=$?
        if ((status == 2)) && grep -qF "has $n lines $name=..., not exactly one" <<<"$out" && cmp -s "$cgen" "$gen"; then
            ok "$line $how: fails (exit 2), writes nothing"
        else
            fail "$line $how (exit $status): $out"
        fi
    done
done
cp "$src" "$copy/onnxruntime-split/PKGBUILD"
# The cuda12 line's stamped lines are not this one's: left as they are.
if grep -qxF '_ortf_default_cuda_archs=rtx' "$cgen" && grep -qxF '_ortf_cuda_major_default=13' "$cgen"; then
    ok "the CUDA defaults are left as the source has them (unused: no CUDA package)"
else
    fail "the CUDA default lines: $(grep -n '^_ortf_default_cuda_archs=\|^_ortf_cuda_major_default=' "$cgen")"
fi

echo "== usage"
for args in '--bogus' '--check extra' '--write'; do
    status=0
    # shellcheck disable=SC2086 # the arguments are words
    "$copy/scripts/gen-migraphx.sh" $args >/dev/null 2>&1 || status=$?
    if ((status == 2)); then ok "usage error for [$args]"; else fail "[$args] exits $status, not 2"; fi
done

if ((fails > 0)); then
    echo "$fails of $count check(s) failed"
    exit 1
fi
echo "all $count checks passed"
